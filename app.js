function showSlide(
    index
) {

    const slides =
        [
            ...document
                .querySelectorAll(
                    ".featured-slide"
                )
        ];


    const dots =
        [
            ...document
                .querySelectorAll(
                    ".carousel-dot"
                )
        ];


    if (
        !slides.length
    ) {

        return;

    }


    if (
        index < 0
    ) {

        index =
            slides.length -
            1;

    }


    if (
        index >=
        slides.length
    ) {

        index =
            0;

    }


    currentSlide =
        index;


    slides.forEach(
        (
            slide,
            position
        ) => {

            slide.classList.toggle(

                "active",

                position ===
                index

            );

        }
    );


    dots.forEach(
        (
            dot,
            position
        ) => {

            dot.classList.toggle(

                "active",

                position ===
                index

            );

        }
    );


    bindTilt();

}


