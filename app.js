function bindLightboxTriggers() {

    document
        .querySelectorAll(
            "[data-lightbox-index]"
        )
        .forEach(
            element => {

                if (
                    element
                        .dataset
                        .lightboxBound
                ) {

                    return;

                }


                element
                    .dataset
                    .lightboxBound =
                    "1";


                element.addEventListener(
                    "click",
                    event => {

                        event.stopPropagation();


                        openLightbox(
                            Number(
                                element
                                    .dataset
                                    .lightboxIndex
                            )
                        );

                    }
                );

            }
        );

}


