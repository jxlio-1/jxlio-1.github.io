function updateScroll() {

    const top =
        window.scrollY;


    const total =
        document.documentElement
            .scrollHeight
        -
        window.innerHeight;


    const progress =
        total > 0

        ?

        (
            top /
            total
        ) * 100

        :

        0;


    scrollProgressBar.style.width =
        `${progress}%`;


    backToTop.classList.toggle(
        "visible",
        top > 500
    );

}


window.addEventListener(
    "scroll",
    updateScroll,
    {
        passive: true
    }
);


updateScroll();


