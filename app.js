const revealObserver =
    new IntersectionObserver(

        entries => {

            entries.forEach(
                entry => {

                    if (
                        !entry.isIntersecting
                    ) {

                        return;

                    }


                    const delay =
                        Number(
                            entry.target
                                .dataset
                                .delay
                            ||
                            0
                        );


                    setTimeout(
                        () => {

                            entry.target
                                .classList
                                .add(
                                    "visible"
                                );

                        },
                        delay
                    );


                    revealObserver
                        .unobserve(
                            entry.target
                        );

                }
            );

        },

        {

            threshold:
                0.12

        }

    );


